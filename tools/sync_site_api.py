#!/usr/bin/env python3
"""Copy the Verified Ask package into the Vercel site so the serverless function can import it.

    python tools/sync_site_api.py          # copy verify/*.py -> site/api/_verify/
    python tools/sync_site_api.py --check  # exit 1 if the copy differs (CI)

Vercel deploys only `site/`, so the function can't import ../verify. The copy is generated, never
edited by hand; the underscore keeps Vercel from treating it as functions.
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC, DST = ROOT / "verify", ROOT / "site" / "api" / "_verify"
FILES = ("__init__.py", "core.py", "sources.py", "server.py")
HEADER = "# GENERATED by tools/sync_site_api.py from verify/{name}. Do not edit; edit verify/ and re-run.\n"


def rendered(name: str) -> str:
    return HEADER.format(name=name) + (SRC / name).read_text()


def main() -> None:
    if "--check" in sys.argv:
        bad = [n for n in FILES if not (DST / n).exists() or (DST / n).read_text() != rendered(n)]
        if bad:
            sys.exit(f"site/api/_verify is out of date: {', '.join(bad)}. Run python tools/sync_site_api.py")
        print("site/api/_verify matches verify/")
        return
    DST.mkdir(parents=True, exist_ok=True)
    for n in FILES:
        (DST / n).write_text(rendered(n))
    print(f"copied {len(FILES)} files to {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
